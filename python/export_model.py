"""Convert the trained Keras model for the ESP32 and test quantization.

    gesture_model.keras ─┬─► TFLite float32 ─┐
                         └─► TFLite INT8    ─┴─► accuracy / agreement / size report
                                              └─► gesture_model.h  (C byte array, 16-byte aligned)
                                                  model_config.h   (classes, NORM_MEAN/STD,
                                                                    quant scale & zero point, ops)

INT8 is full-integer post-training quantization, calibrated on 300 real (normalised, not
augmented) training windows, with int8 input and output tensors. Both .tflite files are run
on the test set and compared with the Keras model.

The two headers are written into firmware/esp32s3_inference/, so the firmware always uses the
same class order and normalisation as training. Nothing is copied by hand.

    python export_model.py                 # deploy float32 (default)
    python export_model.py --deploy int8   # deploy the INT8 model
"""
import argparse
import json
import os
from datetime import datetime
from pathlib import Path

os.environ.setdefault("TF_CPP_MIN_LOG_LEVEL", "2")

import numpy as np
import tensorflow as tf

import config as C
import analyze_live as M  # metrics

N_CALIBRATION = 300


def convert_float32(model):
    return tf.lite.TFLiteConverter.from_keras_model(model).convert()


def convert_int8(model, calib):
    conv = tf.lite.TFLiteConverter.from_keras_model(model)
    conv.optimizations = [tf.lite.Optimize.DEFAULT]

    def representative():
        for w in calib:
            yield [w[None].astype(np.float32)]

    conv.representative_dataset = representative
    conv.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    conv.inference_input_type = tf.int8
    conv.inference_output_type = tf.int8
    return conv.convert()


def tflite_predict(model_bytes, X):
    """Run a .tflite model on normalised windows; returns float probabilities [n, classes]."""
    interp = tf.lite.Interpreter(model_content=model_bytes)
    interp.allocate_tensors()
    inp = interp.get_input_details()[0]
    out = interp.get_output_details()[0]
    in_scale, in_zp = inp["quantization"]
    out_scale, out_zp = out["quantization"]
    probs = []
    for w in X:
        x = w[None].astype(np.float32)
        if inp["dtype"] == np.int8:
            x = np.clip(np.round(x / in_scale + in_zp), -128, 127).astype(np.int8)
        interp.set_tensor(inp["index"], x)
        interp.invoke()
        y = interp.get_tensor(out["index"])[0]
        if out["dtype"] == np.int8:
            y = (y.astype(np.float32) - out_zp) * out_scale
        probs.append(y)
    return np.array(probs)


def tensor_info(model_bytes):
    interp = tf.lite.Interpreter(model_content=model_bytes)
    interp.allocate_tensors()
    inp = interp.get_input_details()[0]
    out = interp.get_output_details()[0]
    try:
        ops = sorted({op["op_name"] for op in interp._get_ops_details()} - {"DELEGATE"})
    except Exception:  # private API; only used for the header comment
        ops = []
    return inp, out, ops


def c_array(name, data):
    lines = [f"alignas(16) const unsigned char {name}[] = {{"]
    for i in range(0, len(data), 12):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 12]) + ",")
    lines.append("};")
    lines.append(f"const unsigned int {name}_len = {len(data)};")
    return "\n".join(lines)


def write_model_header(path, model_bytes, kind):
    stamp = datetime.now().isoformat(timespec="seconds")
    path.write_text(
        f"// Generated by python/export_model.py on {stamp}. Do not edit.\n"
        f"// {kind} TFLite model, {len(model_bytes)} bytes.\n"
        "#pragma once\n#include <stdint.h>\n\n" + c_array("g_gesture_model", model_bytes) + "\n",
        encoding="utf-8")


def write_config_header(path, norm, kind, inp, out, ops, threshold):
    classes = norm["classes"]
    is_int8 = kind == "int8"
    in_scale, in_zp = inp["quantization"] if is_int8 else (1.0, 0)
    out_scale, out_zp = out["quantization"] if is_int8 else (1.0, 0)
    fl = lambda v: ", ".join(f"{x:.8f}f" for x in v)
    rest_index = classes.index(C.REST_CLASS) if C.REST_CLASS in classes else -1
    text = f"""// Generated by python/export_model.py on {datetime.now().isoformat(timespec="seconds")}. Do not edit.
// Keeps the firmware in step with training: class order, normalisation and quantization.
#pragma once

#define MODEL_IS_INT8 {1 if is_int8 else 0}
#define NUM_CLASSES {len(classes)}
#define WINDOW_SIZE {norm["window"]}
#define NUM_AXES {len(norm["axes"])}
#define SAMPLE_RATE_HZ {norm["sample_rate_hz"]}
#define INFERENCE_STRIDE {C.STRIDE}
#define REST_INDEX {rest_index}
#define DEFAULT_THRESHOLD {threshold:.2f}f
#define COOLDOWN_MS {int(C.COOLDOWN_S * 1000)}

static const char* const CLASS_NAMES[NUM_CLASSES] = {{{", ".join(f'"{c}"' for c in classes)}}};
static const char* const CLASS_WORDS[NUM_CLASSES] = {{{", ".join(f'"{C.word(c)}"' for c in classes)}}};

// per-axis z-score: x_norm = (x - NORM_MEAN) / NORM_STD   (axes: {", ".join(norm["axes"])})
static const float NORM_MEAN[NUM_AXES] = {{{fl(norm["mean"])}}};
static const float NORM_STD[NUM_AXES] = {{{fl(norm["std"])}}};

// int8 quantization (unused for float32): q = round(x / scale) + zero_point
static const float INPUT_SCALE = {in_scale:.10f}f;
static const int INPUT_ZERO_POINT = {int(in_zp)};
static const float OUTPUT_SCALE = {out_scale:.10f}f;
static const int OUTPUT_ZERO_POINT = {int(out_zp)};

// operators used by the model: {", ".join(ops) if ops else "n/a"}
"""
    path.write_text(text, encoding="utf-8")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--artifacts", default=str(C.ARTIFACTS_DIR))
    ap.add_argument("--deploy", choices=["float32", "int8"], default="float32")
    ap.add_argument("--firmware-dir", default=str(C.FIRMWARE_INFERENCE_DIR))
    ap.add_argument("--threshold", type=float, default=C.THRESHOLD)
    args = ap.parse_args()

    art = Path(args.artifacts)
    model = tf.keras.models.load_model(art / "gesture_model.keras")
    norm = json.loads((art / "norm_params.json").read_text())
    splits = np.load(art / "splits.npz")
    classes = list(norm["classes"])
    mean, std = np.array(norm["mean"], np.float32), np.array(norm["std"], np.float32)
    X_test = (splits["X_test"] - mean) / std
    y_test = splits["y_test"]
    X_train = (splits["X_train"] - mean) / std
    rng = np.random.default_rng(C.SEED)
    calib = X_train[rng.choice(len(X_train), min(N_CALIBRATION, len(X_train)), replace=False)]

    keras_pred = model.predict(X_test, verbose=0).argmax(axis=1)
    keras_acc = float((keras_pred == y_test).mean())

    models = {"float32": convert_float32(model), "int8": convert_int8(model, calib)}
    rows, results = [], {}
    for kind, data in models.items():
        (art / f"gesture_model_{kind}.tflite").write_bytes(data)
        pred = tflite_predict(data, X_test).argmax(axis=1)
        s = M.summarize(M.confusion(y_test, pred, len(classes)), classes)
        results[kind] = {"size_bytes": len(data), "accuracy": s["accuracy"], "macro_f1": s["macro_f1"],
                         "agreement_keras": float((pred == keras_pred).mean()), "pred": pred}
        print(f"{kind:8s} {len(data) / 1024:7.1f} KB   test acc {s['accuracy']:.4f}   "
              f"agreement with Keras {results[kind]['agreement_keras']:.4f}")
    agree_int8_float = float((results["int8"]["pred"] == results["float32"]["pred"]).mean())
    ratio = results["float32"]["size_bytes"] / results["int8"]["size_bytes"]

    f, q = results["float32"], results["int8"]
    rows = ["# Quantization report", "",
            f"Keras model: {model.count_params():,} parameters · test windows: {len(y_test)} · "
            f"INT8 calibrated on {len(calib)} training windows", "",
            "| | Keras | TFLite float32 | TFLite INT8 |", "|---|---|---|---|",
            f"| Size | — | {f['size_bytes'] / 1024:.1f} KB | {q['size_bytes'] / 1024:.1f} KB ({ratio:.2f}× smaller) |",
            f"| Test accuracy | {keras_acc:.2%} | {f['accuracy']:.2%} | {q['accuracy']:.2%} |",
            f"| Macro F1 | — | {f['macro_f1']:.2%} | {q['macro_f1']:.2%} |",
            f"| Agreement with Keras | — | {f['agreement_keras']:.2%} | {q['agreement_keras']:.2%} |",
            f"| Agreement with float32 | — | — | {agree_int8_float:.2%} |",
            "", f"Deployed to firmware: **{args.deploy}**."]
    (art / "quantization_report.md").write_text("\n".join(rows) + "\n", encoding="utf-8")

    fw = Path(args.firmware_dir)
    fw.mkdir(parents=True, exist_ok=True)
    data = models[args.deploy]
    inp, out, ops = tensor_info(data)
    write_model_header(fw / "gesture_model.h", data, args.deploy)
    write_config_header(fw / "model_config.h", norm, args.deploy, inp, out, ops, args.threshold)
    print("\n".join(rows))
    print(f"\nwrote {fw / 'gesture_model.h'} and {fw / 'model_config.h'} ({args.deploy}); ops: {', '.join(ops)}")


if __name__ == "__main__":
    main()
